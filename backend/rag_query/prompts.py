_TRUE = ("1", "true", "yes", "on")
_FALSE = ("0", "false", "no", "off")


def _prompts_config() -> Dict[str, Any]:
    """Секция 'rag_prompts' из config.yml. Ошибка чтения — пустой словарь.

    Конфиг кэшируется в 'backend.config', так что вызов дешёвый, а промпт
    остаётся правимым через ConfigMap без пересборки образа.
    """
    try:
        from backend.config import get_config

        section = (get_config() or {}).get("rag_prompts")
    except Exception:
        logger.exception("Не удалось прочитать секцию rag_prompts — беру дефолты")
        return {}
    return section if isinstance(section, dict) else {}


def _config_text(key: str) -> Optional[str]:
    texts = _prompts_config().get("texts")
    if not isinstance(texts, dict):
        return None
    raw = texts.get(key)
    if isinstance(raw, str) and raw.strip():
        return raw.strip()
    return None


def _text(key: str) -> str:
    """Текст из config.yml, иначе дефолт модуля."""
    return _config_text(key) or _DEFAULT_TEXTS[key]


def _rule(key: str) -> str:
    """Блок правил с подставленной канонической фразой «не нашёл».

    Подстановка через 'replace', а не 'format': конфиг правят руками,
    и случайная фигурная скобка в тексте не должна ронять сборку промпта.
    """
    return _text(key).replace(_NOT_FOUND_PLACEHOLDER, rag_strict_not_found_message())


def _flag(env_name: str, config_key: str, default: bool) -> bool:
    """ENV > config.yml > дефолт. Нераспознанное значение = как будто не задано."""
    raw = (os.environ.get(env_name) or "").strip().lower()
    if raw in _FALSE:
        return False
    if raw in _TRUE:
        return True
    value = _prompts_config().get(config_key)
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        low = value.strip().lower()
        if low in _FALSE:
            return False
        if low in _TRUE:
            return True
    return default


def _strict_answer_mode() -> str:
    """soft (по умолчанию) | strict.

    soft  — LLM всегда пытается ответить, если в CONTEXT есть хоть какой-то материал,
            и честно указывает, чего не хватает.
    strict — LLM выводит каноническую фразу «не нашёл», если прямой опоры нет.
    """
    raw = (os.environ.get("RAG_STRICT_ANSWER_MODE") or "").strip().lower()
    if not raw:
        raw = str(_prompts_config().get("strict_answer_mode") or "").strip().lower()
    return "strict" if raw in ("strict", "hard", *_TRUE) else "soft"


def rag_strict_not_found_message() -> str:
    """Единственный ответ, который backend отдаёт без вызова LLM."""
    return _text("not_found_message")


def cite_sources_enabled() -> bool:
    """По умолчанию False: ссылки на чанки в ответ пользователя не выводятся."""
    return _flag("RAG_CITE_SOURCES", "cite_sources", False)


def answer_summary_enabled() -> bool:
    """По умолчанию True: ответ завершается кратким итогом."""
    return _flag("RAG_ANSWER_SUMMARY", "answer_summary", True)


def answer_gaps_note_enabled() -> bool:
    """По умолчанию True: абзац «Примечание:» о том, чего нет в документах."""
    return _flag("RAG_ANSWER_GAPS_NOTE", "answer_gaps_note", True)


def documents_inventory_enabled() -> bool:
    """По умолчанию True: перечень доступных файлов в начале CONTEXT.

    Читается дважды и в разных местах: здесь — чтобы подмешать правило, и в
    rag_evidence.build_rag_inventory_block — чтобы вообще не собирать блок.
    Так модули не тянут друг друга ради одного флага, а выключатель остаётся
    один.
    """
    return _flag("RAG_DOCUMENTS_INVENTORY", "documents_inventory", True)


# Значения на момент импорта — их читают модули, которым нужна константа
# ('rag_evidence', 'handlers', 'document_agent'). Правка ConfigMap
# применяется при рестарте пода, как и остальные настройки из config.yml.
RAG_STRICT_NOT_FOUND_MESSAGE = rag_strict_not_found_message()


def _policy_rules() -> str:
    """Политика ответа: что и как отвечать по документам.

    Промпт агента или проекта имеет над ней приоритет — правила всё равно
    отдаются модели, но с явной оговоркой, чью инструкцию слушать при конфликте.
    Так короткий промпт вроде «Ты юрист банка» не стирает молча всю выверенную
    механику работы с контекстом, а дополняет её.
    """
    parts = [
        (
            _rule("strict_context_rules")
            if _strict_answer_mode() == "strict"
            else _rule("soft_context_rules")
        )
    ]
    if documents_inventory_enabled():
        parts.append(_rule("documents_inventory_rule"))
    if answer_gaps_note_enabled():
        parts.append(_rule("gaps_note_rule"))
    if answer_summary_enabled():
        parts.append(_rule("summary_rule"))
    return "\n\n".join(parts)


def mandatory_output_rules(with_citations: Optional[bool] = None) -> str:
    """То, что не отменяется пользовательским промптом ни при каких условиях.

    Две вещи: запрет выдумывать конкретику вместе с канонической фразой отказа
    (```answer_guarantees```) и запрет показывать служебную разметку контекста.
    Обе продуктовые, а не пер-юзерные: выдуманная сумма в ответе или «фрагмент 3»
    на экране — это дефект, а не чья-то настройка.

    ```with_citations``` — явный override над ```cite_sources``` /
    ```RAG_CITE_SOURCES```: None — как в конфиге, True/False — принудительно.
    """
    cite = cite_sources_enabled() if with_citations is None else bool(with_citations)
    return "\n\n".join(
        [
            _rule("answer_guarantees"),
            _rule("citation_rule") if cite else _rule("no_service_markup_rule"),
            # Не зависит от cite_sources: ссылки на источники - это одно,
            # вываленный в ответ текст чанка - другое.
            _rule("no_raw_chunks_rule"),
        ]
    )


def answer_formatting_rules(with_citations: Optional[bool] = None) -> str:
    """Только оформление ответа, без политики «отвечай строго по CONTEXT».

    Нужно там, где текст собирается не из CONTEXT напрямую, а из результатов
    инструментов — в агрегаторе оркестратора. Ему нельзя навязывать правила
    работы с документами (инструмент мог быть и не документный), но тащить
    в ответ «Согласно Фрагменту 1» нельзя тем более: до этой правки агрегатор
    вызывал модель вообще без системного промпта и не знал ни одного запрета.
    """
    cite = cite_sources_enabled() if with_citations is None else bool(with_citations)
    return "\n\n".join(
        [
            _rule("citation_rule") if cite else _rule("no_service_markup_rule"),
            _rule("no_raw_chunks_rule"),
        ]
    )


def _active_rules() -> str:
    """Совместимость: прежнее имя блока правил контекста."""
    return _policy_rules()


def build_rag_user_instruction(with_citations: Optional[bool] = None) -> str:
    """Полный блок правил RAG без пользовательского промпта: политика + гарантии."""
    return f"{_policy_rules()}\n\n{mandatory_output_rules(with_citations)}"


def merge_strict_rag_system_prompt(
    existing: Optional[str], rag_override: Optional[str] = None
) -> str:
    """Добавляет правила CONTEXT к системному промпту при RAG.

    Название сохранено для обратной совместимости; фактически добавляются мягкие
    правила (по умолчанию) либо строгие при 'strict_answer_mode: strict'.

    ```rag_override``` — промпт агента или проекта. Он НЕ заменяет собой общие
    правила: модель получает и его, и политику ответа, плюс явную оговорку, чью
    инструкцию слушать при конфликте. Раньше промпт сущности вырезал политику
    целиком, и короткое «Отвечай кратко» молча уносило с собой и запрет
    выдумывать даты, и каноническую фразу отказа.

    Гарантии (```answer_guarantees```) и запрет служебной разметки идут последними
    и приоритету пользовательского промпта не подчиняются.
    """
    custom = (rag_override or "").strip()
    if custom:
        block = "\n\n".join(
            [
                custom,
                _rule("entity_prompt_precedence"),
                _policy_rules(),
                mandatory_output_rules(),
            ]
        )
    else:
        block = build_rag_user_instruction()
    if not existing or not str(existing).strip():
        return block
    ex = str(existing).strip()
    if block in ex:
        return ex
    if (not custom) and (
        "только предоставленный контекст (CONTEXT)" in ex
        or "Правила ответа по CONTEXT" in ex
    ):
        return ex
    return f"{ex}\n\n{block}"


def prompts_overview() -> Dict[str, object]:
    """Что реально применилось — для стартового лога и диагностики.

    Отвечает на вопрос «промпт правили в ConfigMap, а он точно доехал?»:
    показывает, какие тексты взяты из config.yml, а какие остались дефолтными.
    """
    return {
        "strict_answer_mode": _strict_answer_mode(),
        "cite_sources": cite_sources_enabled(),
        "answer_summary": answer_summary_enabled(),
        "answer_gaps_note": answer_gaps_note_enabled(),
        "texts_from_config": sorted(
            key for key in _DEFAULT_TEXTS if _config_text(key) is not None
        ),
        "texts_from_defaults": sorted(
            key for key in _DEFAULT_TEXTS if _config_text(key) is None
        ),
    }
